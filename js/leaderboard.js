// ===== BIND LEADERBOARD EVENTS =====

function bindLeaderboardEvents(containerElement, storageModule) {
    if (!containerElement) return;

    var currentTab = 'global';
    var currentMode = '';

    // Tab switching
    var tabs = containerElement.querySelectorAll('.lb-tab');
    for (var t = 0; t < tabs.length; t++) {
        tabs[t].addEventListener('click', function () {
            var tab = this.dataset.lbTab;
            currentTab = tab;

            // Update tab styles
            var allTabs = containerElement.querySelectorAll('.lb-tab');
            for (var tt = 0; tt < allTabs.length; tt++) {
                allTabs[tt].className = 'btn btn-sm lb-tab ' + (allTabs[tt].dataset.lbTab === tab ? 'btn-primary active' : 'btn-outline');
            }

            // Show/hide friends section
            var friendsSection = document.getElementById('lbFriendsSection');
            if (friendsSection) {
                friendsSection.style.display = (tab === 'friends') ? 'block' : 'none';
            }

            refreshScores();
        });
    }

    // Mode filter
    var modeFilter = document.getElementById('lbModeFilter');
    if (modeFilter) {
        modeFilter.addEventListener('change', function () {
            currentMode = this.value;
            refreshScores();
        });
    }

    // Search
    var searchBtn = document.getElementById('lbSearchBtn');
    if (searchBtn) {
        searchBtn.addEventListener('click', function () {
            var input = document.getElementById('lbSearchInput');
            if (!input || !input.value.trim()) return;

            var resultsDiv = document.getElementById('lbSearchResults');
            if (resultsDiv) resultsDiv.innerHTML = '<div style="font-size:11px;color:var(--text-muted);padding:6px">Searching...</div>';

            leaderboard.searchPlayers(input.value.trim()).then(function (players) {
                if (!resultsDiv) return;
                if (players.length === 0) {
                    resultsDiv.innerHTML = '<div style="font-size:11px;color:var(--text-muted);padding:6px">No players found.</div>';
                    return;
                }

                var html = '';
                for (var p = 0; p < players.length; p++) {
                    var player = players[p];
                    html += '<div style="display:flex;align-items:center;gap:8px;padding:6px 8px;margin-bottom:3px;background:var(--bg-card);border-radius:var(--radius-md);border:var(--border-card)">' +
                        '<span style="font-size:16px">' + getAvatarEmoji(player.avatar) + '</span>' +
                        '<span style="flex:1;font-size:12px;font-weight:600">' + (player.player_name || 'Anonymous') + '</span>' +
                        '<span style="font-size:10px;color:var(--text-muted)">🏆' + (player.best_score || 0) + '</span>' +
                        '<button class="btn btn-outline btn-sm lb-add-friend" data-friend-id="' + player.player_id + '" style="font-size:10px;padding:2px 8px">+ Add</button>' +
                        '</div>';
                }
                resultsDiv.innerHTML = html;

                // Bind add friend buttons
                var addBtns = resultsDiv.querySelectorAll('.lb-add-friend');
                for (var a = 0; a < addBtns.length; a++) {
                    addBtns[a].addEventListener('click', function () {
                        var friendId = this.dataset.friendId;
                        var btn = this;
                        btn.disabled = true;
                        btn.textContent = '...';
                        leaderboard.sendFriendRequest(friendId).then(function () {
                            btn.textContent = '✓ Sent';
                            btn.style.color = 'var(--accent-green)';
                        }).catch(function () {
                            btn.textContent = '✗';
                            btn.disabled = false;
                        });
                    });
                }
            });
        });
    }

    // Copy player ID
    var playerIdEl = document.getElementById('lbPlayerId');
    if (playerIdEl) {
        playerIdEl.addEventListener('click', function () {
            var fullId = getOrCreatePlayerId();
            if (navigator.clipboard) {
                navigator.clipboard.writeText(fullId).then(function () {
                    playerIdEl.textContent = 'Copied!';
                    setTimeout(function () {
                        playerIdEl.textContent = fullId.substr(0, 8) + '...';
                    }, 2000);
                });
            }
        });
    }

    // Initial load
    refreshScores();
    loadFriendsData();

    function refreshScores() {
        var listEl = document.getElementById('lbScoreList');
        if (listEl) {
            listEl.innerHTML = '<div style="text-align:center;padding:20px;color:var(--text-muted);font-size:12px">Loading...</div>';
        }

        if (!isConfigured()) {
            if (listEl) listEl.innerHTML = '<div style="text-align:center;padding:20px;color:var(--text-muted);font-size:12px">Leaderboard not configured.</div>';
            return;
        }

        var mode = currentMode || null;

        if (currentTab === 'global') {
            leaderboard.getTopScores(mode, 50).then(function (scores) {
                renderScoreEntries(scores, 'lbScoreList');
            });
        } else if (currentTab === 'friends') {
            leaderboard.getFriendScores(mode, 50).then(function (scores) {
                renderScoreEntries(scores, 'lbScoreList');
            });
        } else if (currentTab === 'mybest') {
            // Show all of the player's own scores
            if (!_supabaseClient) {
                if (listEl) listEl.innerHTML = '<div style="text-align:center;padding:20px;color:var(--text-muted);font-size:12px">Not connected.</div>';
                return;
            }

            var playerId = getOrCreatePlayerId();
            var query = _supabaseClient
                .from('leaderboard')
                .select('*')
                .eq('player_id', playerId)
                .order('score', { ascending: false })
                .limit(50);

            if (mode) {
                query = query.eq('mode', mode);
            }

            query.then(function (res) {
                renderScoreEntries(res.data || [], 'lbScoreList');
            }).catch(function () {
                if (listEl) listEl.innerHTML = '<div style="text-align:center;padding:20px;color:var(--text-muted);font-size:12px">Failed to load scores.</div>';
            });
        }
    }

    function loadFriendsData() {
        if (!isConfigured()) return;

        // Load pending requests
        leaderboard.getPendingRequests().then(function (requests) {
            var pendingDiv = document.getElementById('lbPendingRequests');
            if (!pendingDiv) return;

            if (requests.length === 0) {
                pendingDiv.innerHTML = '<div style="font-size:11px;color:var(--text-muted)">No pending requests.</div>';
                return;
            }

            var html = '';
            for (var r = 0; r < requests.length; r++) {
                var req = requests[r];
                html += '<div style="display:flex;align-items:center;gap:6px;padding:6px 8px;margin-bottom:3px;background:var(--bg-card);border-radius:var(--radius-md);border:var(--border-card)">' +
                    '<span style="flex:1;font-size:11px">From: ' + req.player_id.substr(0, 8) + '...</span>' +
                    '<button class="btn btn-green btn-sm lb-accept-req" data-req-id="' + req.id + '" style="font-size:10px;padding:2px 6px">✓</button>' +
                    '<button class="btn btn-red btn-sm lb-decline-req" data-req-id="' + req.id + '" style="font-size:10px;padding:2px 6px">✗</button>' +
                    '</div>';
            }
            pendingDiv.innerHTML = html;

            // Bind accept/decline
            var acceptBtns = pendingDiv.querySelectorAll('.lb-accept-req');
            for (var a = 0; a < acceptBtns.length; a++) {
                acceptBtns[a].addEventListener('click', function () {
                    var reqId = this.dataset.reqId;
                    leaderboard.acceptFriendRequest(reqId).then(function () {
                        loadFriendsData();
                    });
                });
            }

            var declineBtns = pendingDiv.querySelectorAll('.lb-decline-req');
            for (var d = 0; d < declineBtns.length; d++) {
                declineBtns[d].addEventListener('click', function () {
                    var reqId = this.dataset.reqId;
                    leaderboard.declineFriendRequest(reqId).then(function () {
                        loadFriendsData();
                    });
                });
            }
        });

        // Load friends list
        leaderboard.getFriends().then(function (friends) {
            var friendsDiv = document.getElementById('lbFriendsList');
            if (!friendsDiv) return;

            if (friends.length === 0) {
                friendsDiv.innerHTML = '<div style="font-size:11px;color:var(--text-muted)">No friends yet. Search for players above!</div>';
                return;
            }

            var html = '';
            for (var f = 0; f < friends.length; f++) {
                var friend = friends[f];
                html += '<div style="display:flex;align-items:center;gap:8px;padding:6px 8px;margin-bottom:3px;background:var(--bg-card);border-radius:var(--radius-md);border:var(--border-card)">' +
                    '<span style="font-size:16px">' + getAvatarEmoji(friend.avatar) + '</span>' +
                    '<div style="flex:1">' +
                    '<div style="font-size:12px;font-weight:600">' + (friend.player_name || 'Anonymous') + '</div>' +
                    '<div style="font-size:10px;color:var(--text-muted)">🏆 ' + (friend.best_score || 0) + ' · 🔥 ' + (friend.best_streak || 0) + '</div>' +
                    '</div>' +
                    '<button class="btn btn-outline btn-sm lb-invite-friend" data-friend-id="' + friend.player_id + '" style="font-size:10px;padding:2px 6px">🎮 Invite</button>' +
                    '</div>';
            }
            friendsDiv.innerHTML = html;

            // Bind invite buttons
            var inviteBtns = friendsDiv.querySelectorAll('.lb-invite-friend');
            for (var ib = 0; ib < inviteBtns.length; ib++) {
                inviteBtns[ib].addEventListener('click', function () {
                    var friendId = this.dataset.friendId;
                    var roomCode = prompt('Enter a room code to invite your friend:');
                    if (roomCode && roomCode.trim().length > 0) {
                        leaderboard.inviteFriendToMatch(friendId, roomCode.trim().toUpperCase()).then(function () {
                            alert('Invite sent!');
                        }).catch(function () {
                            alert('Failed to send invite.');
                        });
                    }
                });
            }
        });
    }
}

