/**
 * leaderboard.js — Global leaderboard + friends system for Buzzword Dash
 *
 * Uses Supabase (free tier) for persistent storage.
 * Loaded dynamically from CDN — no npm needed, works on GitHub Pages.
 *
 * SETUP: Run the SQL below in your Supabase SQL Editor, then replace
 * SUPABASE_URL and SUPABASE_ANON_KEY with your project values.
 *
 * ---------------------------------------------------------------
 * SQL to run in Supabase SQL Editor:
 * ---------------------------------------------------------------
 *
 * -- Leaderboard table
 * create table if not exists leaderboard (
 *   id bigint generated by default as identity primary key,
 *   player_id text not null,
 *   player_name text not null default 'Anonymous',
 *   avatar text default 'avatar_intern',
 *   score integer not null default 0,
 *   accuracy integer default 0,
 *   best_streak integer default 0,
 *   speed integer default 1,
 *   mode text default 'endless',
 *   badges text[] default '{}',
 *   created_at timestamp with time zone default timezone('utc', now())
 * );
 *
 * -- Friends table
 * create table if not exists friends (
 *   id bigint generated by default as identity primary key,
 *   player_id text not null,
 *   friend_id text not null,
 *   status text default 'pending',
 *   created_at timestamp with time zone default timezone('utc', now()),
 *   unique(player_id, friend_id)
 * );
 *
 * -- Player profiles (for friend lookups)
 * create table if not exists player_profiles (
 *   player_id text primary key,
 *   player_name text not null default 'Anonymous',
 *   avatar text default 'avatar_intern',
 *   badges text[] default '{}',
 *   best_score integer default 0,
 *   best_streak integer default 0,
 *   visible boolean default false,
 *   updated_at timestamp with time zone default timezone('utc', now())
 * );
 *
 * -- Match invites
 * create table if not exists match_invites (
 *   id bigint generated by default as identity primary key,
 *   from_player text not null,
 *   to_player text not null,
 *   room_code text not null,
 *   created_at timestamp with time zone default timezone('utc', now())
 * );
 *
 * -- Row Level Security
 * alter table leaderboard enable row level security;
 * alter table friends enable row level security;
 * alter table player_profiles enable row level security;
 * alter table match_invites enable row level security;
 *
 * create policy "Public read leaderboard" on leaderboard for select using (true);
 * create policy "Public insert leaderboard" on leaderboard for insert with check (true);
 *
 * create policy "Read own friends" on friends for select using (true);
 * create policy "Insert friends" on friends for insert with check (true);
 * create policy "Update own friends" on friends for update using (true);
 *
 * create policy "Public read profiles" on player_profiles for select using (visible = true);
 * create policy "Upsert own profile" on player_profiles for insert with check (true);
 * create policy "Update own profile" on player_profiles for update using (true);
 *
 * create policy "Read own invites" on match_invites for select using (true);
 * create policy "Insert invites" on match_invites for insert with check (true);
 * create policy "Delete own invites" on match_invites for delete using (true);
 *
 * ---------------------------------------------------------------
 */

