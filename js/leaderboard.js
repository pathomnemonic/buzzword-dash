// ===== LEADERBOARD OBJECT =====

var leaderboard = {

    init: function () {
        if (!isConfigured()) {
            return Promise.resolve();
        }
        getOrCreatePlayerId();
        return loadSupabase().catch(function (e) {
            console.warn('Leaderboard: Supabase init failed:', e.message);
        });
    },

    getPlayerId: function () {
        return getOrCreatePlayerId();
    },

    submitScore: function (data) {
        if (!isConfigured() || !_supabaseClient) return Promise.resolve();

        var playerId = getOrCreatePlayerId();

        var scoreInsert = _supabaseClient
            .from('leaderboard')
            .insert({
                player_id: playerId,
                player_name: data.playerName || 'Anonymous',
                avatar: data.avatar || 'avatar_intern',
                score: data.score || 0,
                accuracy: data.accuracy || 0,
                best_streak: data.bestStreak || 0,
                speed: data.speed || 1,
                mode: data.mode || 'endless',
                badges: data.badges || []
            });

        var profileUpsert = _supabaseClient
            .from('player_profiles')
            .upsert({
                player_id: playerId,
                player_name: data.playerName || 'Anonymous',
                avatar: data.avatar || 'avatar_intern',
                badges: data.badges || [],
                best_score: data.score || 0,
                best_streak: data.bestStreak || 0,
                visible: true,
                updated_at: new Date().toISOString()
            }, { onConflict: 'player_id' });

        return Promise.all([scoreInsert, profileUpsert]).catch(function (e) {
            console.warn('Leaderboard: submit failed:', e.message);
        });
    },

    getTopScores: function (mode, limit) {
        if (!isConfigured() || !_supabaseClient) return Promise.resolve([]);

        var query = _supabaseClient
            .from('leaderboard')
            .select('*')
            .order('score', { ascending: false })
            .limit(limit || 50);

        if (mode) {
            query = query.eq('mode', mode);
        }

        return query.then(function (res) {
            return (res.data || []);
        }).catch(function (e) {
            console.warn('Leaderboard: getTopScores failed:', e.message);
            return [];
        });
    },

    getPlayerBest: function (mode) {
        if (!isConfigured() || !_supabaseClient) return Promise.resolve(null);

        var playerId = getOrCreatePlayerId();
        var query = _supabaseClient
            .from('leaderboard')
            .select('*')
            .eq('player_id', playerId)
            .order('score', { ascending: false })
            .limit(1);

        if (mode) {
            query = query.eq('mode', mode);
        }

        return query.then(function (res) {
            return (res.data && res.data.length > 0) ? res.data[0] : null;
        }).catch(function (e) {
            console.warn('Leaderboard: getPlayerBest failed:', e.message);
            return null;
        });
    },

    searchPlayers: function (queryStr) {
        if (!isConfigured() || !_supabaseClient || !queryStr) return Promise.resolve([]);

        return _supabaseClient
            .from('player_profiles')
            .select('*')
            .eq('visible', true)
            .ilike('player_name', '%' + queryStr + '%')
            .limit(20)
            .then(function (res) {
                return (res.data || []);
            }).catch(function (e) {
                console.warn('Leaderboard: searchPlayers failed:', e.message);
                return [];
            });
    },

    sendFriendRequest: function (friendPlayerId) {
        if (!isConfigured() || !_supabaseClient) return Promise.resolve();

        var playerId = getOrCreatePlayerId();
        return _supabaseClient
            .from('friends')
            .insert({
                player_id: playerId,
                friend_id: friendPlayerId,
                status: 'pending'
            }).catch(function (e) {
                console.warn('Leaderboard: sendFriendRequest failed:', e.message);
            });
    },

    acceptFriendRequest: function (requestId) {
        if (!isConfigured() || !_supabaseClient) return Promise.resolve();

        return _supabaseClient
            .from('friends')
            .update({ status: 'accepted' })
            .eq('id', requestId)
            .catch(function (e) {
                console.warn('Leaderboard: acceptFriendRequest failed:', e.message);
            });
    },

    declineFriendRequest: function (requestId) {
        if (!isConfigured() || !_supabaseClient) return Promise.resolve();

        return _supabaseClient
            .from('friends')
            .delete()
            .eq('id', requestId)
            .catch(function (e) {
                console.warn('Leaderboard: declineFriendRequest failed:', e.message);
            });
    },

    getFriends: function () {
        if (!isConfigured() || !_supabaseClient) return Promise.resolve([]);

        var playerId = getOrCreatePlayerId();

        // Get friends where current player is either player_id or friend_id
        var q1 = _supabaseClient
            .from('friends')
            .select('*')
            .eq('player_id', playerId)
            .eq('status', 'accepted');

        var q2 = _supabaseClient
            .from('friends')
            .select('*')
            .eq('friend_id', playerId)
            .eq('status', 'accepted');

        return Promise.all([q1, q2]).then(function (results) {
            var friendIds = [];
            var rows1 = (results[0].data || []);
            var rows2 = (results[1].data || []);

            for (var i = 0; i < rows1.length; i++) {
                friendIds.push(rows1[i].friend_id);
            }
            for (var j = 0; j < rows2.length; j++) {
                friendIds.push(rows2[j].player_id);
            }

            if (friendIds.length === 0) return [];

            // Fetch profiles for friends
            return _supabaseClient
                .from('player_profiles')
                .select('*')
                .in('player_id', friendIds)
                .then(function (res) {
                    return (res.data || []);
                });
        }).catch(function (e) {
            console.warn('Leaderboard: getFriends failed:', e.message);
            return [];
        });
    },

    getPendingRequests: function () {
        if (!isConfigured() || !_supabaseClient) return Promise.resolve([]);

        var playerId = getOrCreatePlayerId();
        return _supabaseClient
            .from('friends')
            .select('*')
            .eq('friend_id', playerId)
            .eq('status', 'pending')
            .order('created_at', { ascending: false })
            .then(function (res) {
                return (res.data || []);
            }).catch(function (e) {
                console.warn('Leaderboard: getPendingRequests failed:', e.message);
                return [];
            });
    },

    getFriendScores: function (mode, limit) {
        if (!isConfigured() || !_supabaseClient) return Promise.resolve([]);

        var self = this;
        return self.getFriends().then(function (friends) {
            if (friends.length === 0) return [];

            var friendIds = friends.map(function (f) { return f.player_id; });
            // Include current player in friend leaderboard
            friendIds.push(getOrCreatePlayerId());

            var query = _supabaseClient
                .from('leaderboard')
                .select('*')
                .in('player_id', friendIds)
                .order('score', { ascending: false })
                .limit(limit || 50);

            if (mode) {
                query = query.eq('mode', mode);
            }

            return query.then(function (res) {
                return (res.data || []);
            });
        }).catch(function (e) {
            console.warn('Leaderboard: getFriendScores failed:', e.message);
            return [];
        });
    },

    inviteFriendToMatch: function (friendPlayerId, roomCode) {
        if (!isConfigured() || !_supabaseClient) return Promise.resolve();

        var playerId = getOrCreatePlayerId();
        return _supabaseClient
            .from('match_invites')
            .insert({
                from_player: playerId,
                to_player: friendPlayerId,
                room_code: roomCode
            }).catch(function (e) {
                console.warn('Leaderboard: inviteFriendToMatch failed:', e.message);
            });
    },

    checkInvites: function () {
        if (!isConfigured() || !_supabaseClient) return Promise.resolve([]);

        var playerId = getOrCreatePlayerId();
        return _supabaseClient
            .from('match_invites')
            .select('*')
            .eq('to_player', playerId)
            .order('created_at', { ascending: false })
            .limit(5)
            .then(function (res) {
                var invites = res.data || [];
                // Delete read invites
                if (invites.length > 0) {
                    var ids = invites.map(function (inv) { return inv.id; });
                    _supabaseClient
                        .from('match_invites')
                        .delete()
                        .in('id', ids)
                        .catch(function () { /* ignore cleanup errors */ });
                }
                return invites;
            }).catch(function (e) {
                console.warn('Leaderboard: checkInvites failed:', e.message);
                return [];
            });
    },

    subscribeToInvites: function (callback) {
        if (!isConfigured() || !_supabaseClient) return null;

        var playerId = getOrCreatePlayerId();
        try {
            var channel = _supabaseClient
                .channel('match-invites-' + playerId)
                .on('postgres_changes', {
                    event: 'INSERT',
                    schema: 'public',
                    table: 'match_invites',
                    filter: 'to_player=eq.' + playerId
                }, function (payload) {
                    if (callback) callback(payload.new);
                })
                .subscribe();
            return channel;
        } catch (e) {
            console.warn('Leaderboard: subscribeToInvites failed:', e.message);
            return null;
        }
    }
};

