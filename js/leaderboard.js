// ===== HELPER: Load Supabase client from CDN =====

function loadSupabase() {
    if (_supabaseClient) return Promise.resolve(_supabaseClient);
    if (_supabaseLoadPromise) return _supabaseLoadPromise;

    _supabaseLoadPromise = new Promise(function (resolve, reject) {
        // Check if already loaded
        if (window.supabase && window.supabase.createClient) {
            _supabaseClient = window.supabase.createClient(SUPABASE_URL, SUPABASE_ANON_KEY);
            resolve(_supabaseClient);
            return;
        }

        var existing = document.querySelector('script[data-buzzword-supabase]');
        if (existing) {
            existing.addEventListener('load', function () {
                if (window.supabase && window.supabase.createClient) {
                    _supabaseClient = window.supabase.createClient(SUPABASE_URL, SUPABASE_ANON_KEY);
                    resolve(_supabaseClient);
                } else {
                    reject(new Error('Supabase loaded but createClient unavailable'));
                }
            });
            existing.addEventListener('error', function () {
                reject(new Error('Failed to load Supabase'));
            });
            return;
        }

        var script = document.createElement('script');
        script.src = 'https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2/dist/umd/supabase.min.js';
        script.async = true;
        script.dataset.buzzwordSupabase = 'true';

        script.onload = function () {
            if (window.supabase && window.supabase.createClient) {
                _supabaseClient = window.supabase.createClient(SUPABASE_URL, SUPABASE_ANON_KEY);
                resolve(_supabaseClient);
            } else {
                reject(new Error('Supabase loaded but createClient unavailable'));
            }
        };

        script.onerror = function () {
            reject(new Error('Failed to load Supabase from CDN'));
        };

        document.head.appendChild(script);
    });

    return _supabaseLoadPromise;
}

// ===== HELPER: Get or create player ID =====

function getOrCreatePlayerId() {
    if (_playerId) return _playerId;

    try {
        _playerId = localStorage.getItem(PLAYER_ID_KEY);
    } catch (e) {
        // localStorage unavailable
    }

    if (!_playerId) {
        if (typeof crypto !== 'undefined' && crypto.randomUUID) {
            _playerId = crypto.randomUUID();
        } else {
            _playerId = 'player_' + Date.now() + '_' + Math.random().toString(36).substr(2, 9);
        }
        try {
            localStorage.setItem(PLAYER_ID_KEY, _playerId);
        } catch (e) {
            // localStorage unavailable
        }
    }

    return _playerId;
}

